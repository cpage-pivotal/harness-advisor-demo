#!/usr/bin/env bash
set -euo pipefail

kind="${1:-}"
if [[ "$kind" != "patch" && "$kind" != "upgrade" ]]; then
  echo "Usage: $0 {patch|upgrade}" >&2
  exit 2
fi
if [[ -z "${GH_TOKEN:-}" ]]; then
  echo "Set GH_TOKEN to a GitHub token that can push branches and create PRs." >&2
  exit 1
fi
command -v gh >/dev/null || { echo "GitHub CLI (gh) is required." >&2; exit 1; }

repo_root="$(git rev-parse --show-toplevel)"
cd "$repo_root"
if [[ "$(git branch --show-current)" != "demo" ]]; then
  echo "Check out the demo branch before publishing a PR." >&2
  exit 1
fi
if [[ -z "$(git status --porcelain -- pom.xml src .advisor.yml)" ]]; then
  echo "No Application Advisor changes to publish."
  exit 0
fi

branch="advisor-${kind}-$(date -u +%Y%m%d-%H%M%S)"
git config user.name "Harness Application Advisor Demo"
git config user.email "harness-advisor-demo@users.noreply.github.com"
gh auth setup-git
git switch -c "$branch"
git add -- pom.xml src .advisor.yml
git commit -m "demo: apply Application Advisor ${kind}"
git push -u origin "$branch"
gh pr create --base demo --head "$branch" \
  --title "Application Advisor: ${kind} PetClinic" \
  --body "Generated by the Harness Application Advisor demo. Review the dependency changes and Maven test result before merging."
